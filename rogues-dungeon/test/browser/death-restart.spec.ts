import { expect, test } from "@playwright/test";
import { createAdventureLevelBaseline, createRunCampaign } from "../../src/systems/procedural/world-procedural-system.ts";
import { openSavedGame } from "./start-saved-game.ts";

for (const itemTest of [false, true]) test(`@smoke Restart Level keeps Level 2 and reveals a fresh playable scene, item test ${itemTest}`, async ({ page }) => {
  const campaign = createRunCampaign(32, 1, 1, 2, 2, { mode: "adventure" });
  campaign.adventureBaseline = createAdventureLevelBaseline(campaign);
  campaign.player.resources.health.current = 0;
  campaign.floor.entities = campaign.floor.entities.filter(entity => entity.kind !== "enemy");
  const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  page.on("console", message => { if (message.type() === "error") errors.push(message.text()); });
  await page.addInitScript(saved => localStorage.setItem("rogues-dungeon.slot.1", JSON.stringify(saved)), campaign);
  await page.goto("/blockchain-rogues-dungeon-game/?mute=1");
  await openSavedGame(page);
  if (itemTest) await page.getByRole("button", { name: "I: 0", exact: true }).click();
  const world = page.locator(".world-view");
  await expect(world).toHaveAttribute("data-world-alive", "true");
  const context = await world.getAttribute("data-map-context");
  const originalCanvas = await world.locator("canvas").elementHandle();
  await page.keyboard.press("x");
  const recap = page.getByRole("dialog", { name: "YOU DIED", exact: true });
  await expect(recap).toBeVisible({ timeout: 15_000 });
  await expect(recap).toContainText("Level 2");
  await recap.getByRole("button", { name: "Restart Level", exact: true }).click();
  await expect(recap).toHaveCount(0);
  await expect(world).toHaveAttribute("data-renderer-ready", "true", { timeout: 30_000 });
  await expect(world).toHaveAttribute("data-world-alive", "true", { timeout: 15_000 });
  await expect(world).toHaveAttribute("data-map-context", context!);
  await expect(world.locator(".ui_iris_transition")).toHaveCount(0, { timeout: 15_000 });
  expect(await originalCanvas!.evaluate(canvas => canvas.isConnected)).toBe(false);
  const png = await world.locator("canvas").screenshot();
  const visiblePixels = await page.evaluate(async base64 => {
    const bitmap = await createImageBitmap(await (await fetch(`data:image/png;base64,${base64}`)).blob());
    const canvas = new OffscreenCanvas(bitmap.width, bitmap.height);
    const ctx = canvas.getContext("2d")!;
    ctx.drawImage(bitmap, 0, 0);
    const pixels = ctx.getImageData(0, 0, bitmap.width, bitmap.height).data;
    bitmap.close();
    let lit = 0;
    for (let i = 0; i < pixels.length; i += 4) if (Math.max(pixels[i]!, pixels[i + 1]!, pixels[i + 2]!) > 20) lit++;
    return lit;
  }, png.toString("base64"));
  expect(visiblePixels).toBeGreaterThan(1000);
  await page.keyboard.press("x");
  await expect.poll(() => page.evaluate(() => JSON.parse(localStorage.getItem("rogues-dungeon.slot.1")!).floor.time)).toBeGreaterThan(0);
  await expect(recap).toHaveCount(0);
  expect(errors).toEqual([]);
});
